import { intervalOverlappingDaysDateTime } from "./intervalOverlappingDaysDateTime";
import { mockTemporalPlainDateTimeFromThrow } from "../../test/mocks";

describe("intervalOverlappingDaysDateTime", () => {
  it.each`
    aStart                     | aEnd                       | bStart                     | bEnd                       | expected
    ${"2024-01-01T23:59:00"}   | ${"2024-01-02T00:01:00"}   | ${"2024-01-01T23:59:00"}   | ${"2024-01-02T00:01:00"}   | ${2}
    ${"2024-01-01T00:00:00"}   | ${"2024-01-05T00:00:00"}   | ${"2024-01-03T12:00:00"}   | ${"2024-01-09T00:00:00"}   | ${3}
    ${"2014-01-10T00:00:00"}   | ${"2014-01-20T00:00:00"}   | ${"2014-01-17T00:00:00"}   | ${"2014-01-21T00:00:00"}   | ${4}
  `(
    "returns $expected shared dates for $aStart..$aEnd × $bStart..$bEnd",
    ({ aStart, aEnd, bStart, bEnd, expected }) => {
      expect(
        intervalOverlappingDaysDateTime(aStart, aEnd, bStart, bEnd),
      ).toBe(expected);
    },
  );

  it.each`
    aStart                     | aEnd                       | bStart                     | bEnd                       | expected
    ${"2024-01-01T12:00:00"}   | ${"2024-01-01T12:00:00"}   | ${"2024-01-01T12:00:00"}   | ${"2024-01-01T12:00:00"}   | ${1}
    ${"2024-01-01T00:00:00"}   | ${"2024-01-02T00:00:00"}   | ${"2024-01-02T00:00:00"}   | ${"2024-01-03T00:00:00"}   | ${1}
  `(
    "returns $expected for adjacent/identical $aStart..$aEnd × $bStart..$bEnd",
    ({ aStart, aEnd, bStart, bEnd, expected }) => {
      expect(
        intervalOverlappingDaysDateTime(aStart, aEnd, bStart, bEnd),
      ).toBe(expected);
    },
  );

  it.each`
    aStart                     | aEnd                       | bStart                        | bEnd
    ${"2024-01-01T00:00:00"}   | ${"2024-01-02T00:00:00"}   | ${"2024-01-02T00:00:00.001"}  | ${"2024-01-03T00:00:00"}
  `(
    "returns 0 for disjoint $aStart..$aEnd × $bStart..$bEnd",
    ({ aStart, aEnd, bStart, bEnd }) => {
      expect(
        intervalOverlappingDaysDateTime(aStart, aEnd, bStart, bEnd),
      ).toBe(0);
    },
  );

  it.each`
    aStart                     | aEnd                       | bStart                     | bEnd
    ${"2024-06-30T00:00:00"}   | ${"2024-01-01T00:00:00"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T00:00:00"}   | ${"2024-06-15T00:00:00"}   | ${"2024-06-10T00:00:00"}
  `(
    "returns null for inverted interval $aStart..$aEnd × $bStart..$bEnd",
    ({ aStart, aEnd, bStart, bEnd }) => {
      expect(
        intervalOverlappingDaysDateTime(aStart, aEnd, bStart, bEnd),
      ).toBeNull();
    },
  );

  it.each`
    aStart                   | aEnd                     | bStart                   | bEnd
    ${"invalid"}             | ${"2024-06-30T23:59:59"} | ${"2024-04-01T00:00:00"} | ${"2024-12-31T23:59:59"}
    ${""}                    | ${"2024-06-30T23:59:59"} | ${"2024-04-01T00:00:00"} | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"} | ${"invalid"}             | ${"2024-04-01T00:00:00"} | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"} | ${""}                    | ${"2024-04-01T00:00:00"} | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"} | ${"2024-06-30T23:59:59"} | ${"invalid"}             | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"} | ${"2024-06-30T23:59:59"} | ${""}                    | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"} | ${"2024-06-30T23:59:59"} | ${"2024-04-01T00:00:00"} | ${"invalid"}
    ${"2024-01-01T00:00:00"} | ${"2024-06-30T23:59:59"} | ${"2024-04-01T00:00:00"} | ${""}
  `(
    "returns null for malformed datetime: $aStart, $aEnd, $bStart, $bEnd",
    ({ aStart, aEnd, bStart, bEnd }) => {
      expect(
        intervalOverlappingDaysDateTime(aStart, aEnd, bStart, bEnd),
      ).toBeNull();
    },
  );

  it.each`
    aStart                     | aEnd                       | bStart                     | bEnd
    ${null}                    | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${undefined}                | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${123}                     | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${true}                    | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${[]}                      | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${{}}                      | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${null}                    | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${undefined}               | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${123}                     | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${true}                    | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${[]}                      | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${{}}                      | ${"2024-04-01T00:00:00"}   | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${null}                    | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${undefined}               | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${123}                     | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${true}                    | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${[]}                      | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${{}}                      | ${"2024-12-31T23:59:59"}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${null}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${undefined}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${123}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${true}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${[]}
    ${"2024-01-01T00:00:00"}   | ${"2024-06-30T23:59:59"}   | ${"2024-04-01T00:00:00"}   | ${{}}
  `(
    "returns null for non-string input: $aStart, $aEnd, $bStart, $bEnd",
    ({ aStart, aEnd, bStart, bEnd }) => {
      expect(
        intervalOverlappingDaysDateTime(
          aStart as never,
          aEnd as never,
          bStart as never,
          bEnd as never,
        ),
      ).toBeNull();
    },
  );

  it("returns null when Temporal.PlainDateTime.from throws", () => {
    mockTemporalPlainDateTimeFromThrow();
    expect(
      intervalOverlappingDaysDateTime(
        "2024-01-01T00:00:00",
        "2024-06-30T23:59:59",
        "2024-04-01T00:00:00",
        "2024-12-31T23:59:59",
      ),
    ).toBeNull();
  });
});
