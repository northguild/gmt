import {
  mockTemporalInstantFromEpochNanosecondsThrow,
  mockTemporalPlainDateTimeFromThrow,
  mockTemporalPlainTimeFromThrow,
} from "../../test/mocks";
import { fromTT } from "./fromTT";
import { toTT } from "./toTT";

describe("fromTT", () => {
  // UTC = TT − 32.184 s − (TAI − UTC), the Leap_Second.dat row in force.
  it.each`
    ttString                              | expected                            | why
    ${"2026-01-01T00:01:09.184 TT"}       | ${"2026-01-01T00:00:00Z"}           | ${"69.184 s"}
    ${"2017-01-01T00:01:09.184 TT"}       | ${"2017-01-01T00:00:00Z"}           | ${"37 s row, after the insertion"}
    ${"1972-01-01T00:00:42.184 TT"}       | ${"1972-01-01T00:00:00Z"}           | ${"10 s row, the first TT instant of the table"}
    ${"9999-12-31T23:59:59.999999999 TT"} | ${"9999-12-31T23:58:50.815999999Z"} | ${"the last four-digit TT label"}
    ${"9999-12-31T23:59:59.184 TT"}       | ${"9999-12-31T23:58:50Z"}           | ${"TT is 69.184 s ahead in 9999"}
    ${"9999-12-31T23:59:59 TT"}           | ${"9999-12-31T23:58:49.816Z"}       | ${"whole-second label, fraction in the result"}
    ${"1972-01-01T00:00:42.184000001 TT"} | ${"1972-01-01T00:00:00.000000001Z"} | ${"1 ns after the first instant"}
    ${"2026-01-01T00:01:09.185 TT"}       | ${"2026-01-01T00:00:00.001Z"}       | ${"shortest fraction"}
    ${"2026-01-01T00:01:10 TT"}           | ${"2026-01-01T00:00:00.816Z"}       | ${"whole-second label gives a fraction"}
    ${"2026-01-01T00:01:09 TT"}           | ${"2025-12-31T23:59:59.816Z"}       | ${"UTC is still in the previous year"}
  `("returns $expected for $ttString ($why)", ({ ttString, expected }) => {
    expect(fromTT(ttString)).toBe(expected);
  });

  // Inside an inserted second UTC reads 23:59:60 (ITU-R TF.460-6 Annex 3).
  it.each`
    ttString                              | expected
    ${"2017-01-01T00:01:08.184 TT"}       | ${"2016-12-31T23:59:60Z"}
    ${"2017-01-01T00:01:08.684 TT"}       | ${"2016-12-31T23:59:60.5Z"}
    ${"2017-01-01T00:01:08.999999999 TT"} | ${"2016-12-31T23:59:60.815999999Z"}
    ${"2017-01-01T00:01:09 TT"}           | ${"2016-12-31T23:59:60.816Z"}
    ${"2017-01-01T00:01:07.999999999 TT"} | ${"2016-12-31T23:59:59.815999999Z"}
    ${"2015-07-01T00:01:07.184 TT"}       | ${"2015-06-30T23:59:60Z"}
  `(
    "returns the inserted second $expected for $ttString",
    ({ ttString, expected }) => {
      expect(fromTT(ttString)).toBe(expected);
    },
  );

  it.each`
    ttString                              | why
    ${"1972-01-01T00:00:42.183999999 TT"} | ${"1 ns before the table's first instant"}
    ${"2026-01-01T00:01:09.184 TAI"}      | ${"wrong token"}
    ${"2016-12-31T23:59:60 TT"}           | ${"TT has no second 60"}
    ${"2026-01-01T00:01:09.184 TDT"}      | ${"deprecated FITS token"}
    ${"2026-01-01T00:01:09.184 ET"}       | ${"deprecated FITS token"}
    ${"2026-01-01T00:01:09.184 tt"}       | ${"lower case"}
    ${"2026-01-01T00:01:09.184TT"}        | ${"no space"}
    ${"2026-01-01T00:01:09.184  TT"}      | ${"two spaces"}
    ${"2026-02-30T00:00:00 TT"}           | ${"no such day"}
    ${"2026-01-01T24:00:00 TT"}           | ${"hour 24"}
    ${"0000-01-01T00:00:00 TT"}           | ${"before 1972"}
    ${"1972-01-01T00:00:00 TT"}           | ${"label 1972, 42.184 s before the first instant"}
    ${"1971-12-31T23:59:59.999999999 TT"} | ${"1 ns before 1972"}
  `("returns '' for $ttString ($why)", ({ ttString }) => {
    expect(fromTT(ttString)).toBe("");
  });

  it.each`
    ttString     | label
    ${123}       | ${"123"}
    ${null}      | ${"null"}
    ${undefined} | ${"undefined"}
    ${""}        | ${"''"}
  `("returns '' for the non-time-scale $label", ({ ttString }) => {
    expect(fromTT(ttString)).toBe("");
  });

  it("returns '' when Temporal.PlainDateTime.from throws", () => {
    mockTemporalPlainDateTimeFromThrow();
    expect(fromTT("2026-01-01T00:01:09.184 TT")).toBe("");
  });

  it("returns '' when Temporal.Instant.fromEpochNanoseconds throws while writing", () => {
    mockTemporalInstantFromEpochNanosecondsThrow();
    expect(fromTT("2026-01-01T00:01:09.184 TT")).toBe("");
  });

  it("returns '' when Temporal.PlainTime.from throws while writing second 60", () => {
    mockTemporalPlainTimeFromThrow();
    expect(fromTT("2017-01-01T00:01:08.184 TT")).toBe("");
  });
});

// Every inserted leap second: the TT seconds before, during and after read back as
