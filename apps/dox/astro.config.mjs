import { referenceSidebar } from "./src/generated/reference/sidebar.ts";
import { industriesSidebar } from "./src/generated/industries-sidebar.ts";
import { toolsSidebar } from "./src/generated/tools-sidebar.ts";
import { scenariosSidebar } from "./src/generated/scenarios-sidebar.ts";
import { mistakesSidebar } from "./src/generated/mistakes-sidebar.ts";
import { guidesIndustriesSidebar } from "./src/generated/guides-industries-sidebar.ts";
import rehypeBaseLinks from "./src/lib/rehype-base-links.ts";
import rehypeExternalLinks from "./src/lib/rehype-external-links.ts";
import rehypeTableScroll from "./src/lib/rehype-table-scroll.ts";
import { copyRedirects } from "./src/lib/copy-redirects.ts";
import { gmtReferenceWatch } from "./src/lib/gmt-reference-watch.ts";
import { devWorkerProxy } from "./src/lib/dev-worker-proxy.ts";
import { SITE_BASE, SITE_ORIGIN, withBase } from "./src/lib/site.ts";

// `site` + `base` make every Starlight link, the canonical tag, the sitemap
// and Pagefind resolve under /gmt/. One module holds both, for the Worker and
// the scripts too.

const gmtPkg = fileURLToPath(
  new URL("../../packages/gmt/dist", import.meta.url),
);

/* The Guides section: its index, then one autogenerated group per folder, named by the folder
   as Starlight names it. The "industries" folder is the exception: its pages are grouped by
   industry under a divider, as Tools, Scenarios and Mistakes are
   (`scripts/build-industry-sidebars.ts`). */
const GUIDE_FOLDERS = readdirSync(
  fileURLToPath(new URL("./src/content/docs/guides", import.meta.url)),
  { withFileTypes: true },
)
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const guidesSidebar = [
  { slug: "guides" },
  ...GUIDE_FOLDERS.map((folder) =>
    folder === "industries"
      ? {
          label: folder,
          collapsed: true,
          items: guidesIndustriesSidebar,
        }
      : {
          label: folder,
          collapsed: true,
          items: [
            {
              autogenerate: { directory: `guides/${folder}`, collapsed: true },
            },
          ],
        },
  ),
];

export default defineConfig({
  site: SITE_ORIGIN,
  base: SITE_BASE,
  // Cloudflare looks assets up by the full request path (serving a
  // subdirectory: developers.cloudflare.com/workers/static-assets/routing/
  // advanced/serving-a-subdirectory/), so the files must sit at dist/gmt/…
  // while wrangler.jsonc keeps `directory: "./dist"`.
  outDir: "./dist/gmt",
  markdown: {
    // External links in Markdown and MDX open in a new tab, like ButtonLink's do. Every table
    // sits in the site's table scroll box, so it fills the column.
    rehypePlugins: [rehypeBaseLinks, rehypeExternalLinks, rehypeTableScroll],
  },
  vite: {
    server: {
      // `/gmt/api/…` lives in the Cloudflare Worker, which `astro dev` doesn't run.
      // Proxy it to a local `wrangler dev` (`pnpm dev` starts both, on
      // DOX_WORKER_PORT). Why the key is not `/gmt/api`: src/lib/dev-worker-proxy.ts.
      proxy: devWorkerProxy(process.env.DOX_WORKER_PORT),
    },
    plugins: [tailwindcss()],
    css: {
      // Component kit (src/widgets): one CSS Module per component. Names are
      // readable and stable (`gmt-range__thumb`), so html-diff stays legible and
      // never churns on a content edit. `camelCaseOnly` gives `styles.thumb`.
      modules: {
        localsConvention: "camelCaseOnly",
        generateScopedName: (
          /** @type {string} */ local,
          /** @type {string} */ file,
        ) =>
          `gmt-${basename(file.split("?")[0] ?? file, ".module.css")}__${local}`,
      },
    },
    // One dependency cache per dev server. Two `astro dev` processes sharing
    // node_modules/.vite re-optimise each other's deps, and the first server
    // then answers 504 "Outdated Optimize Dep" for every pre-bundled import
    // (the globe's @tanstack/virtual-core first). A second server on the
    // same checkout sets DOX_VITE_CACHE_DIR to a folder of its own.
    cacheDir: process.env.DOX_VITE_CACHE_DIR || undefined,
    optimizeDeps: {
      // Astro points Vite's startup dependency scan at .jsx/.tsx/.vue/.svelte/
      // .html only. Every widget, chart and globe is an .astro <script> into a
      // plain .ts module under src/lib, so their packages (@tanstack/charts,
      // d3-geo, topojson-client, …) were discovered only when a page first
      // imported them. Vite then re-bundled and force-reloaded every open page,
      // and any dynamic import in flight — a widget's chunk — failed with
      // "Failed to fetch dynamically imported module" (seen 2026-09-24). Scanning
      // src/lib finds them at startup instead. Tests and the server-only
      // retrieval modules are left out; they never reach a browser.
      entries: [
        "src/lib/**/*.ts",
        "!src/lib/**/*.test.ts",
        "!src/lib/retrieval/**",
      ],
    },
    build: {
      // Baseline 2024: the oldest of each engine that `npx browserslist "baseline 2024"` lists.
      cssTarget: ["chrome130", "edge130", "firefox132", "safari18.2"],
      cssMinify: "esbuild",
    },
    resolve: {
      alias: {
        "@northguild/gmt": gmtPkg,
      },
    },
  },
  integrations: [
    // Dev only (its hook is `astro:server:setup`): regenerates the API reference
    // when gmt source changes, so a JSDoc edit shows up without a restart.
    gmtReferenceWatch(),
    // Build only: puts src/generated/_redirects at dist/_redirects, above outDir.
    copyRedirects(),
    react(),
    starlight({
      title: "@northguild/gmt",
      description:
        "Date and time library for JavaScript and TypeScript, built on TC39 Temporal: time zones, DST, business days, ISO 8601 strings in and out. Never throws.",
      // Adds the share, breadcrumb and Markdown-twin tags to each page's head (src/route-data.ts).
      routeMiddleware: "./src/route-data.ts",
      // Each page shows the date of its last commit (CI checks out the full history). No page
      // carries an edit link; scripts/head-tags.test.ts fails on one.
      lastUpdated: true,
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/northguild/gmt",
        },
        {
          icon: "discord",
          label: "Discord",
          href: "https://discord.gg/TdvQdP3t5a",
        },
      ],
      // The Dox crystal, hand-authored in public/favicon.svg. Without this
      // Starlight falls back to its own default of '/favicon.svg' — a file
      // that did not exist, so every page in the site was requesting it and
      // being served the 404 page. The PNG fallbacks, for browsers that
      // cannot use an SVG icon, are in `head` below.
      favicon: "/favicon.svg",
      // Inline the code-block styles instead of linking `ec.<hash>.css`.
      // Expressive Code emits that <link> inside <body>, at the first code
      // block, and the browser holds back everything after an in-body
      // stylesheet until it has loaded — so on each route change the page
      // painted with an empty gap below the first heading for a frame. An
      // inline <style> applies as it is parsed. Costs ~4 KB gzipped per page.
      expressiveCode: { emitExternalStylesheet: false },
      // Preload the self-hosted display font (vendored to `public/fonts/`, see
      // gmt-tokens.css). Without this the browser only discovers the @font-face
      // after the CSS bundle parses, so the site title and every heading
      // reflow out of the mono fallback on each navigation — the "header flash".
      head: [
        {
          tag: "link",
          attrs: {
            rel: "preload",
            href: withBase("/fonts/michroma-latin-400-normal.woff2"),
            as: "font",
            type: "font/woff2",
            crossorigin: "anonymous",
          },
        },
        // Hold the first paint until the end-of-page marker (src/components/
        // Footer.astro) is parsed. On a route change the browser keeps showing
        // the old page until the new one first paints; without this that
        // happens mid-parse, so the header, sidebar and content appear in
        // separate frames — the "flash". Browsers without `rel="expect"`
        // ignore it, and blocking always ends when parsing finishes, so a
        // page without the marker still renders.
        // https://html.spec.whatwg.org/multipage/links.html#link-type-expect
        {
          tag: "link",
          attrs: {
            rel: "expect",
            href: "#gmt-page-end",
            blocking: "render",
          },
        },
        // DOX-A3b: discoverability — let LLMs find the llms.txt surface
        {
          tag: "link",
          attrs: {
            rel: "alternate",
            type: "text/plain",
            href: withBase("/llms.txt"),
          },
        },
        /* Raster fallbacks for the SVG favicon above, generated from it by
           `pnpm run favicons`. Starlight sorts its own `rel="shortcut icon"`
           entry *after* extra icon links precisely so the SVG wins wherever
           it is supported (see its utils/head.ts), which makes this the
           fallback rather than the winner. Rendered at the exact size the
           browser asks for, so falling back never means downscaling. */
        {
          tag: "link",
          attrs: {
            rel: "icon",
            type: "image/png",
            sizes: "32x32",
            href: withBase("/favicon-32.png"),
          },
        },
        {
          tag: "link",
          attrs: {
            rel: "apple-touch-icon",
            sizes: "180x180",
            href: withBase("/apple-touch-icon.png"),
          },
        },
        {
          tag: "script",
          content: `(() => {
            const el = document.documentElement;
            el.classList.add('is-scrolling');
            let t;
            const end = () => {
              clearTimeout(t);
              t = setTimeout(() => el.classList.remove('is-scrolling'), 500);
            };
            window.addEventListener('scroll', end, { passive: true });
          })();`,
        },
      ],
      /* Every group starts collapsed except Checks, the last group, which
         lists the checks for recent tz rule changes. Starlight still opens any group that
         contains the current page (SidebarSublist: open when an entry is
         current or the group is not collapsed), so a page opens only its own
         ancestors. */
      sidebar: [
        {
          label: "Start here",
          collapsed: true,
          items: [
            { slug: "why-gmt" },
            { slug: "compare" },
            { slug: "upstream" },
            { slug: "core-rules" },
            { slug: "install" },
            { slug: "bundle-size" },
          ],
        },
        {
          label: "Migrate",
          collapsed: true,
          items: [
            { slug: "migrate" },
            { slug: "migrate/date-fns" },
            { slug: "migrate/luxon" },
            { slug: "migrate/dayjs" },
            { slug: "migrate/moment" },
            { slug: "migrate/internationalized-date" },
            { slug: "migrate/temporal" },
            { slug: "compare/behaviour" },
          ],
        },
        { label: "Industries", collapsed: true, items: industriesSidebar },
        { label: "API Reference", collapsed: true, items: referenceSidebar },
        {
          label: "Guides",
          collapsed: true,
          items: guidesSidebar,
        },
        {
          label: "Tools",
          collapsed: true,
          items: toolsSidebar,
        },
        {
          label: "Scenarios",
          collapsed: true,
          items: scenariosSidebar,
        },
        {
          label: "Mistakes",
          collapsed: true,
          items: mistakesSidebar,
        },
        {
          label: "Checks",
          collapsed: false,
          items: [{ autogenerate: { directory: "check" } }],
        },
      ],
      components: {
        Head: "./src/components/Head.astro",
        Header: "./src/components/Header.astro",
        Footer: "./src/components/Footer.astro",
        ThemeProvider: "./src/components/ThemeProvider.astro",
        ThemeSelect: "./src/components/ThemeSelect.astro",
        Hero: "./src/components/Hero.astro",
        PageTitle: "./src/components/PageTitle.astro",
        Sidebar: "./src/components/Sidebar.astro",
        SocialIcons: "./src/components/SocialIcons.astro",
        SiteTitle: "./src/components/SiteTitle.astro",
      },
      customCss: [
        "./src/styles/gmt.css", // layer order + every global sheet, each in its gmt.* layer
      ],
    }),
    // After starlight(): Starlight adds its own sitemap only when none is configured. /dox/ is
    // the chat shell and has `noindex`, so it is not listed.
    sitemap({
      filter: (page) => new URL(page).pathname !== withBase("/dox/"),
    }),
  ],
});
