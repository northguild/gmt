#!/usr/bin/env tsx
/**
 * Generate the MCP tool list.
 *
 * Imports every module in src/lib/webmcp/tools/ once, reads its `def`, and writes
 * src/generated/mcp-tools.json (the listing, plus slug, industries and example) and
 * src/generated/mcp-tool-loaders.ts (tool name to a dynamic import). The Worker's `tools/list` reads
 * the JSON and never evaluates a tool module; `tools/call` loads only the module it calls.
 *
 * Needs packages/gmt/dist: the tool modules import the built library.
 *
 * Run as: tsx apps/dox/scripts/build-mcp-tools.ts
 */

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { toolListing, type PageToolDef } from "../src/lib/webmcp/page-tool";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = resolve(appRoot, "src", "lib", "webmcp", "tools");
const generatedDir = resolve(appRoot, "src", "generated");

if (!existsSync(resolve(appRoot, "..", "..", "packages", "gmt", "dist"))) {
  throw new Error(
    "[mcp] packages/gmt/dist is missing. Run: pnpm --filter @northguild/gmt build",
  );
}

const industriesFile = resolve(generatedDir, "tool-industries.json");
if (!existsSync(industriesFile)) {
  throw new Error(
    "[mcp] src/generated/tool-industries.json is missing. Run build-tool-index.ts first",
  );
}
const industriesBySlug = JSON.parse(
  readFileSync(industriesFile, "utf8"),
) as Record<string, string[]>;

const slugs = readdirSync(toolsDir)
  .filter((file) => file.endsWith(".ts") && !file.endsWith(".test.ts"))
  .map((file) => file.slice(0, -".ts".length))
  .sort();

const entries: (ReturnType<typeof toolListing> & {
  slug: string;
  industries: string[];
  example: unknown;
})[] = [];
const seen = new Map<string, string>();
for (const slug of slugs) {
  const mod = (await import(
    pathToFileURL(resolve(toolsDir, `${slug}.ts`)).href
  )) as { def?: PageToolDef };
  if (!mod.def) throw new Error(`[mcp] tools/${slug}.ts has no \`def\` export`);
  const def = mod.def;
  const industries = industriesBySlug[slug];
  if (!industries || industries.length === 0) {
    throw new Error(`[mcp] ${slug} has no industries in tool-industries.json`);
  }
  const clash = seen.get(def.name);
  if (clash) {
    throw new Error(
      `[mcp] tools/${slug}.ts and tools/${clash}.ts both name "${def.name}"`,
    );
  }
  seen.set(def.name, slug);
  entries.push({ ...toolListing(def), slug, industries, example: def.example });
}
entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const json = `${JSON.stringify(entries, null, 2)}\n`;
const loaders = `// Generated by scripts/build-mcp-tools.ts. Do not edit; run \`pnpm --filter @gmt/dox generate\`.
import type { PageToolDef } from "../lib/webmcp/page-tool";

export const MCP_TOOL_LOADERS: Record<string, () => Promise<{ def: PageToolDef }>> = {
${entries
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.name)}: () => import("../lib/webmcp/tools/${entry.slug}"),`,
  )
  .join("\n")}
};
`;

mkdirSync(generatedDir, { recursive: true });
writeFileSync(resolve(generatedDir, "mcp-tools.json"), json);
writeFileSync(resolve(generatedDir, "mcp-tool-loaders.ts"), loaders);
console.log(
  `[mcp] wrote ${entries.length} tools, ${json.length} bytes of JSON`,
);
